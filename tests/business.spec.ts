test('cajero sin permiso no cambia catálogo ni puede autoasignarse administrador', async ({ page, context }) => {
  await mockAuth(context, { profile: { id:authUser.id,display_name:'Cajero',role:'cashier',active:true } })
  await page.goto('/#/inventario')
  await expect(page.getByRole('heading',{name:'Inventario',exact:true})).toHaveCount(0)
  await expect(page.getByRole('heading',{name:'Punto de venta',exact:true})).toBeVisible()
  await expect(page.getByRole('button',{name:'Nuevo producto',exact:true})).toHaveCount(0)
  const result = await page.evaluate(async () => {
    const response = await fetch('https://cai-api-test.invalid/api/operations', {
      method:'POST',headers:{Authorization:'Bearer fake.payload.signature','Content-Type':'application/json'},
      body:JSON.stringify({action:'user.save',data:{role:'admin'},key:'forged-profile'}),
    })
    return {status:response.status,body:await response.json()}
  })
  expect(result).toMatchObject({status:403,body:{error:{code:'FORBIDDEN'}}})
  await page.goto('/#/configuracion')
  await expect(page.getByRole('alert')).toContainText('No tienes permiso')
})

test('cambiar el pago invalida la confirmación manual y un total incorrecto no crea venta', async ({ page }) => {
  await page.goto('/#/pos')
  await page.getByRole('button',{name:'Agregar Café de origen 500 g',exact:true}).click()
  await page.getByLabel('Pago Efectivo',{exact:true}).fill('28500')
  const confirmation = page.getByRole('checkbox',{name:/Confirmo los pagos recibidos/})
  await confirmation.check()
  await expect(page.getByRole('button',{name:'Registrar venta',exact:true})).toBeEnabled()
  await page.getByLabel('Pago Efectivo',{exact:true}).fill('28499')
  await expect(confirmation).not.toBeChecked()
  await expect(page.getByRole('button',{name:'Registrar venta',exact:true})).toBeDisabled()
  await confirmation.check()
  await page.getByRole('button',{name:'Registrar venta',exact:true}).click()
  await expect(page.getByRole('alert')).toContainText('Los pagos deben coincidir')
  await expect(page.locator('tbody tr')).toHaveCount(0)
})

test('cajero solo ve POS y Deudas; hashes y solicitudes administrativas quedan bloqueadas', async ({ page, context }) => {
  await mockAuth(context, { profile: { id: authUser.id, display_name: 'Cajero V1.1', role: 'cashier', active: true } })
  await page.goto('/#/pos')
  await expect(page.getByRole('heading', { name: 'Punto de venta', exact: true })).toBeVisible()
  const menu = page.getByRole('navigation')
  await expect(menu.getByRole('link')).toHaveCount(2)
  await expect(menu.getByRole('link', { name: 'Deudas', exact: true })).toBeVisible()
  await page.getByRole('textbox', { name: 'Buscar módulos' }).fill('inventario')
  await expect(page.locator('.search-results').getByRole('link')).toHaveCount(0)
  for (const route of ['inventario', 'contabilidad', 'estadisticas', 'proveedores', 'configuracion', 'auditoria', 'clientes']) {
    await page.goto(`/#/${route}`)
    await expect(page.getByRole('alert')).toContainText('No tienes permiso')
    await expect(page.getByRole('heading', { name: 'Punto de venta', exact: true })).toBeVisible()
  }
  const statuses = await page.evaluate(async () => Promise.all(['report', 'cash.move', 'reset.confirm', 'user.save', 'sale.return'].map(async (action) => {
    const response = await fetch('https://cai-api-test.invalid/api/operations', { method: 'POST', headers: { Authorization: 'Bearer fake.payload.signature', 'Content-Type': 'application/json' }, body: JSON.stringify({ action, data: {}, key: 'forged-v11' }) })
    return response.status
  })))
  expect(statuses).toEqual([403, 403, 403, 403, 403])
})


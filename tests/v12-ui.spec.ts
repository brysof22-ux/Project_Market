test('admin reemplaza Nequi y Bre-B de forma independiente y rechaza archivo inválido',async({page,context})=>{
 await mockAuth(context)
 await page.goto('/#/configuracion')
 const nequi=page.getByRole('img',{name:'Código QR Nequi',exact:true}), breb=page.getByRole('img',{name:'Código QR Llaves Bre-B',exact:true})
 await expect(nequi).toBeVisible();await expect(breb).toBeVisible()
 const digest = (image: Locator) => image.evaluate(async (img) => { const bytes=await (await fetch((img as HTMLImageElement).src)).arrayBuffer(); return Array.from(new Uint8Array(await crypto.subtle.digest('SHA-256',bytes)),b=>b.toString(16).padStart(2,'0')).join('') }).catch(() => null)
 const initialNequi=await digest(nequi), initialBreb=await digest(breb)
 await page.getByLabel('Reemplazar QR Nequi',{exact:true}).setInputFiles('tests/fixtures/qr-demo.jpg')
 await page.getByRole('button',{name:'Guardar QR Nequi',exact:true}).click()
 await expect.poll(async()=>{const current=await digest(nequi);return current !== null && current !== initialNequi}).toBe(true)
 await expect.poll(()=>digest(breb)).toBe(initialBreb)
 const changedNequi=await digest(nequi)
 await page.getByLabel('Reemplazar QR Llaves Bre-B',{exact:true}).setInputFiles('tests/fixtures/qr-demo.webp')
 await page.getByRole('button',{name:'Guardar QR Llaves Bre-B',exact:true}).click()
 await expect.poll(async()=>{const current=await digest(breb);return current !== null && current !== initialBreb}).toBe(true)
 await expect.poll(()=>digest(nequi)).toBe(changedNequi)
 await page.getByLabel('Reemplazar QR Nequi',{exact:true}).setInputFiles({name:'malicioso.svg',mimeType:'image/svg+xml',buffer:Buffer.from('<svg/>')})
 await expect(page.getByRole('alert')).toContainText('Usa PNG')
 await page.setViewportSize({width:390,height:844})
 await expect(breb).toBeVisible()
 await page.screenshot({path:'.cache/v12-mobile.png',fullPage:true})
 expect(await page.evaluate(()=>document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
})

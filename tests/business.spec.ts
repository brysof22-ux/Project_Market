test('producto nuevo y entrada auditada sobreviven recarga con existencias reales', async ({ page }) => {
  await page.goto('/#/inventario')
  await page.getByRole('button', { name:'Nuevo producto',exact:true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Nombre', {exact:true}).fill('Producto persistente')
  await expect(dialog.getByLabel('SKU', {exact:true})).toHaveCount(0)
  await expect(dialog.getByLabel('Código de barras', {exact:true})).toHaveCount(0)
  await expect(dialog.getByLabel('Categoría', {exact:true})).toHaveCount(0)
  await dialog.getByLabel('Precio de venta').fill('150000')
  await dialog.getByLabel('Precio de compra').fill('90000')
  await dialog.getByRole('button',{name:'Guardar producto',exact:true}).click()
  await expect(page.getByRole('status').filter({hasText:'Operación guardada.'})).toBeVisible()
  await page.getByRole('button',{name:'Mover Producto persistente',exact:true}).click()
  await page.getByLabel('Cantidad de movimiento').fill('20')
  await page.getByLabel('Motivo',{exact:true}).fill('Compra inicial recibida')
  await page.getByRole('button',{name:'Registrar movimiento',exact:true}).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.reload()
  await expect(page.locator('tbody tr').filter({hasText:'Producto persistente'})).toContainText('20 unidades')
  await page.getByRole('button',{name:'Historial Producto persistente',exact:true}).click()
  await expect(page.getByRole('dialog')).toContainText('Compra inicial recibida')
})


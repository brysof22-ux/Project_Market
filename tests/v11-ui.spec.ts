test('dos ventas a crédito para homónimos generan identidades distintas y abono dirigido', async ({ page, context }) => {
  await mockAuth(context, { profile: { id: authUser.id, display_name: 'Cajero V1.1', role: 'cashier', active: true } })
  await page.goto('/#/pos')
  for (let index = 0; index < 2; index++) {
    await page.getByRole('button', { name: 'Agregar Café de origen 500 g', exact: true }).click()
    await page.getByRole('checkbox', { name: 'Vender a crédito', exact: true }).check()
    await page.getByLabel('Nombre completo', { exact: true }).fill('Persona homónima')
    await page.getByLabel('Teléfono', { exact: true }).fill('3001234567')
    await page.getByLabel('Pago Efectivo', { exact: true }).fill('1000')
    await page.getByRole('checkbox', { name: /Confirmo los pagos recibidos/ }).check()
    await page.getByRole('button', { name: 'Registrar venta', exact: true }).click()
    await expect(page.getByRole('status').filter({ hasText: 'Venta registrada en la tienda.' })).toBeVisible()
  }
  await page.goto('/#/creditos')
  await expect(page.getByRole('heading', { name: 'Deudas', exact: true })).toBeVisible()
  const rows = page.locator('tbody tr')
  await expect(rows).toHaveCount(2)
  const customerIds = await rows.locator('td:first-child small:last-child').allTextContents()
  expect(new Set(customerIds).size).toBe(2)
  await rows.first().getByRole('button', { name: 'Ver deuda de Persona homónima' }).click()
  await page.getByLabel('Valor del abono', { exact: true }).fill('500')
  await page.getByRole('checkbox', { name: 'Confirmo el valor recibido.' }).check()
  await page.getByRole('button', { name: 'Registrar abono recibido', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Abono registrado en esta compra.' })).toBeVisible()
  await expect(rows.filter({ hasText: '27.000' })).toHaveCount(1)
  await expect(rows.filter({ hasText: '27.500' })).toHaveCount(1)
  await page.screenshot({ path: 'test-results/v11-deudas.png', fullPage: true })
})

test('fotografía privada adjunta se conserva al recargar inventario y se muestra en POS', async ({ page }) => {
  await page.goto('/#/inventario')
  await page.getByRole('button', { name: 'Editar Café de origen 500 g', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Fotografía del producto').setInputFiles('tests/fixtures/qr-demo.jpg')
  const upload = page.waitForResponse((response) => response.url().endsWith('/image') && response.request().method() === 'POST')
  await dialog.getByRole('button', { name: 'Guardar producto', exact: true }).click()
  const result = await upload
  expect({ status: result.status(), code: (await result.json()).error?.code }).toMatchObject({ status: 201 })
  await expect(dialog).toHaveCount(0)
  await page.reload()
  const image = page.getByRole('img', { name: 'Café de origen 500 g', exact: true })
  await expect(image).toBeVisible()
  await expect.poll(() => image.evaluate((element: HTMLImageElement) => element.naturalWidth)).toBeGreaterThan(0)
  await page.screenshot({ path: 'test-results/v11-inventario.png', fullPage: true })
  await page.goto('/#/pos')
  await expect(page.getByRole('button', { name: 'Agregar Café de origen 500 g', exact: true }).getByRole('img', { name: 'Café de origen 500 g', exact: true })).toBeVisible()
  await page.screenshot({ path: 'test-results/v11-pos.png', fullPage: true })
})

